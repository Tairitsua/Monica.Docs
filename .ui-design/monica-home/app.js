async function copyActiveCode() {
    const activePanel = document.querySelector("[data-code-panel]:not([hidden])");
    const code = activePanel.querySelector("code").textContent;
    const status = document.getElementById("copy-status");

    try {
        if (navigator.clipboard && window.isSecureContext) {
            await navigator.clipboard.writeText(code);
        } else {
            const fallback = document.createElement("textarea");
            fallback.value = code;
            fallback.setAttribute("readonly", "");
            fallback.style.position = "fixed";
            fallback.style.opacity = "0";
            document.body.appendChild(fallback);
            fallback.select();
            document.execCommand("copy");
            fallback.remove();
        }
        status.textContent = currentLanguage === "zh" ? "已复制到剪贴板" : "Copied to clipboard";
    } catch {
        status.textContent = currentLanguage === "zh" ? "请选择代码并手动复制" : "Select the code to copy manually";
    }

    window.setTimeout(() => {
        status.textContent = "";
    }, 2200);
}

