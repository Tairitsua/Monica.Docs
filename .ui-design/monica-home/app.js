function setupRevealObserver() {
    const sections = document.querySelectorAll(".reveal-section");
    if (reducedMotion.matches || !("IntersectionObserver" in window)) {
        sections.forEach((section) => section.classList.add("is-visible"));
        return;
    }

    const observer = new IntersectionObserver((entries) => {
        entries.forEach((entry) => {
            if (entry.isIntersecting) {
                entry.target.classList.add("is-visible");
                observer.unobserve(entry.target);
            }
        });
    }, { rootMargin: "0px 0px -12%", threshold: 0.08 });

    sections.forEach((section) => observer.observe(section));
}

function initializeLanguage() {
    let savedLanguage = "en";
    try {
        savedLanguage = window.localStorage.getItem("monica-home-language") || "en";
    } catch {
        savedLanguage = "en";
    }
    setLanguage(savedLanguage === "zh" ? "zh" : "en");
}

function initialize() {
    if (window.lucide) {
        window.lucide.createIcons();
    }

    initializeLanguage();
    setupRevealObserver();

    document.getElementById("language-toggle").addEventListener("click", () => {
        setLanguage(currentLanguage === "en" ? "zh" : "en");
    });

    document.getElementById("menu-toggle").addEventListener("click", (event) => {
        setMobileMenu(event.currentTarget.getAttribute("aria-expanded") !== "true");
    });

    document.querySelectorAll(".mobile-nav a").forEach((link) => {
        link.addEventListener("click", () => setMobileMenu(false));
    });

    document.addEventListener("keydown", (event) => {
        if (event.key === "Escape") setMobileMenu(false);
    });

    document.querySelectorAll(".scenario-chip").forEach((button) => {
        button.addEventListener("click", () => activateScenario(button));
    });
    document.getElementById("replay-trace").addEventListener("click", replayTrace);

    document.querySelectorAll(".code-tab").forEach((button) => {
        button.addEventListener("click", () => activateCodeTab(button));
    });
    setupTabKeyboard(".code-tab", activateCodeTab);
    document.getElementById("copy-code").addEventListener("click", copyActiveCode);

    document.querySelectorAll(".surface-tab").forEach((button) => {
        button.addEventListener("click", () => activateSurfaceTab(button));
    });
    setupTabKeyboard(".surface-tab", activateSurfaceTab);

    document.querySelectorAll(".tier-filter").forEach((button) => {
        button.addEventListener("click", () => activateTier(button));
    });

    window.addEventListener("scroll", () => {
        document.getElementById("site-header").classList.toggle("is-scrolled", window.scrollY > 12);
    }, { passive: true });

    reducedMotion.addEventListener?.("change", replayTrace);
    replayTrace();
}

document.addEventListener("DOMContentLoaded", initialize);
