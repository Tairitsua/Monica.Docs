function clearTraceTimers() {
    traceTimers.forEach((timer) => window.clearTimeout(timer));
    traceTimers = [];
}

function replayTrace() {
    clearTraceTimers();

    const stages = [...document.querySelectorAll("[data-trace-stage]")];
    const connectors = [...document.querySelectorAll(".trace-connector")];
    stages.forEach((stage) => stage.classList.remove("is-active", "is-complete"));
    connectors.forEach((connector) => connector.classList.remove("is-active"));

    const status = document.getElementById("trace-status");
    const doneMessage = currentLanguage === "zh"
        ? `${scenarioData[currentScenario].unit} 架构轨迹已完成。`
        : `${scenarioData[currentScenario].unit} architecture trace completed.`;

    if (reducedMotion.matches) {
        stages.forEach((stage) => stage.classList.add("is-complete"));
        connectors.forEach((connector) => connector.classList.add("is-active"));
        status.textContent = doneMessage;
        return;
    }

    stages.forEach((stage, index) => {
        const startTimer = window.setTimeout(() => {
            if (index > 0) {
                stages[index - 1].classList.remove("is-active");
                stages[index - 1].classList.add("is-complete");
                connectors[index - 1].classList.add("is-active");
            }
            stage.classList.add("is-active");
        }, 120 + index * 360);
        traceTimers.push(startTimer);
    });

    const finishTimer = window.setTimeout(() => {
        stages.at(-1).classList.remove("is-active");
        stages.at(-1).classList.add("is-complete");
        status.textContent = doneMessage;
    }, 120 + stages.length * 360);
    traceTimers.push(finishTimer);
}

function activateScenario(button) {
    document.querySelectorAll(".scenario-chip").forEach((chip) => {
        const active = chip === button;
        chip.classList.toggle("is-active", active);
        chip.setAttribute("aria-pressed", String(active));
    });
    populateScenario(button.dataset.scenario);
    replayTrace();
}

function activateTab(button, options) {
    const { buttonSelector, panelSelector, dataKey, activeValue } = options;

    document.querySelectorAll(buttonSelector).forEach((tab) => {
        const active = tab === button;
        tab.classList.toggle("is-active", active);
        tab.setAttribute("aria-selected", String(active));
        tab.tabIndex = active ? 0 : -1;
    });

    document.querySelectorAll(panelSelector).forEach((panel) => {
        const active = panel.dataset[dataKey] === activeValue;
        panel.hidden = !active;
        panel.classList.toggle("is-active", active);
    });
}

function setupTabKeyboard(buttonSelector, activation) {
    const tabs = [...document.querySelectorAll(buttonSelector)];
    tabs.forEach((tab, index) => {
        tab.addEventListener("keydown", (event) => {
            if (!["ArrowLeft", "ArrowRight", "Home", "End"].includes(event.key)) {
                return;
            }

            event.preventDefault();
            let nextIndex = index;
            if (event.key === "ArrowRight") nextIndex = (index + 1) % tabs.length;
            if (event.key === "ArrowLeft") nextIndex = (index - 1 + tabs.length) % tabs.length;
            if (event.key === "Home") nextIndex = 0;
            if (event.key === "End") nextIndex = tabs.length - 1;
            tabs[nextIndex].focus();
            activation(tabs[nextIndex]);
        });
    });
}

