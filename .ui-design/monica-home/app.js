function setTextTranslations(language) {
    const languageSet = translations[language];

    document.querySelectorAll("[data-i18n]").forEach((element) => {
        const key = element.dataset.i18n;
        if (languageSet[key]) {
            element.textContent = languageSet[key];
        }
    });

    document.documentElement.lang = language === "zh" ? "zh-CN" : "en";
    document.title = language === "zh"
        ? "Monica — 可观测的 .NET 应用架构"
        : "Monica — Observable .NET application architecture";

    const description = document.querySelector('meta[name="description"]');
    description.content = language === "zh"
        ? "Monica 为 .NET 团队提供智能体可遵循、人类可检查的应用架构。"
        : "Monica gives .NET teams architecture agents can follow and systems humans can inspect.";

    const toggle = document.getElementById("language-toggle");
    toggle.innerHTML = language === "zh"
        ? '<span>EN</span><span aria-hidden="true">/</span><span class="language-active">中文</span>'
        : '<span class="language-active">EN</span><span aria-hidden="true">/</span><span>中文</span>';
    toggle.setAttribute("aria-label", language === "zh" ? "Switch to English" : "切换到中文");

    const menuToggle = document.getElementById("menu-toggle");
    const menuOpen = menuToggle.getAttribute("aria-expanded") === "true";
    menuToggle.setAttribute("aria-label", language === "zh"
        ? (menuOpen ? "关闭导航" : "打开导航")
        : (menuOpen ? "Close navigation" : "Open navigation"));

    document.getElementById("surface-caption").textContent = surfaceData[currentSurface].caption[language];
    document.getElementById("tier-description").textContent = tierDescriptions[currentTier][language];
    populateScenario(currentScenario);
}

